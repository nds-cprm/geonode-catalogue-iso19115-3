"""
Refreshes the local copy of the XSD files used to validate the metadata.

Downloads the root schema of each format and, recursively, every
``xs:import``, ``xs:include`` and ``xs:redefine``. Files are written mirroring
the ``host/path`` of their URL, with ``schemaLocation`` rewritten as relative
paths, so validation works without the network.

    python manage.py fetch_metadata_schemas [--output DIR] [--cache DIR]

Without ``--output``, the files go to ``settings.CATALOGUE_METADATA_SCHEMAS_DIR``
or, when it is not set, to the ``schemas/`` directory of the package.
"""

import os
import pathlib
import shutil
import tempfile
import time
import urllib.parse
import urllib.request

from django.core.management.base import BaseCommand, CommandError
from lxml import etree

from ...validation import SCHEMA_ROOTS, local_schema_path, schemas_dir

XS = "{http://www.w3.org/2001/XMLSchema}"
REFERENCES = (XS + "import", XS + "include", XS + "redefine")


def _parse(data):
    return etree.fromstring(data, etree.XMLParser(resolve_entities=False, no_network=True))


class Command(BaseCommand):
    help = "Downloads the XSD files of the metadata formats for offline validation."

    def add_arguments(self, parser):
        parser.add_argument("--output", help="Target directory (default: the configured schemas directory).")
        parser.add_argument("--cache", help="Directory to keep the original files and reuse them.")
        parser.add_argument("--retries", type=int, default=3)

    def _download(self, url, dest, retries):
        for attempt in range(1, retries + 1):
            try:
                request = urllib.request.Request(url, headers={"User-Agent": "geonode-catalogue-iso19115-3"})
                with urllib.request.urlopen(request, timeout=60) as response:
                    data = response.read()
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_bytes(data)
                return
            except OSError as err:
                if attempt == retries:
                    raise CommandError(f"Could not download {url}: {err}")
                time.sleep(2 * attempt)

    def handle(self, *args, **options):
        target_dir = pathlib.Path(options["output"]) if options["output"] else schemas_dir()
        cache = pathlib.Path(options["cache"] or tempfile.mkdtemp(prefix="iso-xsd-"))
        out = pathlib.Path(tempfile.mkdtemp(prefix="iso-xsd-out-"))

        seen = set()
        todo = list(SCHEMA_ROOTS.values())
        while todo:
            url = todo.pop()
            if url in seen:
                continue
            seen.add(url)

            raw = local_schema_path(cache, url)
            if not raw.exists():
                self.stdout.write(f"downloading {url}")
                self._download(url, raw, options["retries"])

            doc = _parse(raw.read_bytes())
            target = local_schema_path(out, url)
            for el in doc.iter(*REFERENCES):
                location = el.get("schemaLocation")
                if not location:
                    continue
                ref_url = urllib.parse.urljoin(url, location)
                todo.append(ref_url)
                el.set("schemaLocation", os.path.relpath(local_schema_path(out, ref_url), target.parent))

            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(etree.tostring(doc, xml_declaration=True, encoding="UTF-8"))

        (out / "README.md").write_text(
            "Local copy of the XSD files used by `geonode_catalogue_iso19115_3.validation`.\n\n"
            "Generated by `python manage.py fetch_metadata_schemas`; do not edit by hand. The files mirror the\n"
            "`host/path` of their original URLs, with `schemaLocation` rewritten as relative paths.\n\n"
            "Roots:\n\n" + "".join(f"- {fmt}: {url}\n" for fmt, url in SCHEMA_ROOTS.items())
        )

        if target_dir.exists():
            shutil.rmtree(target_dir)
        shutil.copytree(out, target_dir)
        shutil.rmtree(out)
        self.stdout.write(self.style.SUCCESS(f"{len(seen)} schemas written to {target_dir}"))
