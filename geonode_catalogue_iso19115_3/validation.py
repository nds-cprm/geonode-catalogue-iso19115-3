"""
Validation of the metadata XML against the XSD of its format.

The schemas live in ``schemas/`` (a local copy generated by
``python manage.py fetch_metadata_schemas``), so validation does not use the
network. Another directory can be used with
``settings.CATALOGUE_METADATA_SCHEMAS_DIR``. Loading the schema takes a few
seconds; it is loaded once per process.
"""

import functools
import pathlib
import urllib.parse

from django.conf import settings
from lxml import etree

from .constants import ISO19115_3

PACKAGE_SCHEMAS_DIR = pathlib.Path(__file__).resolve().parent / "schemas"

# format -> URL of the root schema
SCHEMA_ROOTS = {
    ISO19115_3: "https://schemas.isotc211.org/19115/-3/mdb/2.0/mdb.xsd",
}


class SchemaNotAvailable(Exception):
    pass


def schemas_dir():
    return pathlib.Path(getattr(settings, "CATALOGUE_METADATA_SCHEMAS_DIR", None) or PACKAGE_SCHEMAS_DIR)


def local_schema_path(base, url):
    parsed = urllib.parse.urlparse(url)
    return pathlib.Path(base) / parsed.netloc / parsed.path.lstrip("/")


def _schema_path(fmt):
    url = SCHEMA_ROOTS.get(fmt)
    if url is None:
        raise SchemaNotAvailable(f"There is no XSD configured for the {fmt!r} format.")
    path = local_schema_path(schemas_dir(), url)
    if not path.exists():
        raise SchemaNotAvailable(f"{path} does not exist. Run `python manage.py fetch_metadata_schemas`.")
    return path


@functools.lru_cache(maxsize=None)
def _load_schema(path):
    parser = etree.XMLParser(no_network=True, resolve_entities=False)
    return etree.XMLSchema(etree.parse(str(path), parser))


def get_schema(fmt):
    return _load_schema(_schema_path(fmt))


def validate_xml(xml, fmt=ISO19115_3):
    """
    Validates ``xml`` (str or bytes) against the XSD of the format.

    Returns the list of errors, empty when the document is valid. Each error is
    ``"line N: message"``.
    """
    if isinstance(xml, str):
        xml = xml.encode("utf-8")
    try:
        doc = etree.fromstring(xml, etree.XMLParser(no_network=True, resolve_entities=False))
    except etree.XMLSyntaxError as err:
        return [f"Malformed XML: {err}"]
    schema = get_schema(fmt)
    if schema.validate(doc):
        return []
    return [f"line {e.line}: {e.message}" for e in schema.error_log]
